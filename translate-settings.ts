import * as fs from 'fs';
import { Project, SyntaxKind } from 'ts-morph';

const project = new Project({ tsConfigFilePath: 'tsconfig.json' });

let keyCounter = 1;
const toAdd: string[] = [];

const processFile = (filePath: string) => {
  const sourceFile = project.getSourceFile(filePath);
  if (!sourceFile) return;

  let modified = false;

  const replaceNode = (node: any, isJsxText: boolean) => {
    const text = isJsxText ? node.getText().trim() : node.getLiteralText().trim();
    if (translations[text] || Object.keys(translations).some(k => text.includes(k) && k.length > 20)) {
       // Exact or partial match
       let matchText = text;
       if (!translations[text]) matchText = Object.keys(translations).find(k => text.includes(k) && k.length > 20)!;
       
       const key = `settings.auto.${keyCounter++}`;
       toAdd.push(`  '${key}': '${translations[matchText].en}', // AR: ${matchText}`);
       
       if (isJsxText) {
          node.replaceWithText(node.getText().replace(matchText, `{t('${key}')}`));
       } else {
          const parent = node.getParent();
          if (parent.getKind() === SyntaxKind.JsxAttribute) {
             node.replaceWithText(`{t('${key}')}`);
          } else {
             node.replaceWithText(`t('${key}')`);
          }
       }
       modified = true;
    }
  };

  sourceFile.forEachDescendant((node) => {
    if (node.getKind() === SyntaxKind.JsxText) replaceNode(node, true);
    else if (node.getKind() === SyntaxKind.StringLiteral) replaceNode(node, false);
  });

  if (modified) sourceFile.saveSync();
};

processFile('src/components/worklog/SettingsView.tsx');

fs.writeFileSync('auto-lang-additions.txt', toAdd.join('\n'));
